package terminal

import (
	"image/color"

	"github.com/charmbracelet/x/ansi"
)

// The emulator presents itself as a dark terminal (Tomorrow Night), so
// programs that ask pick their dark themes, and renders read like the
// terminals people use.
var (
	themeFg     = color.RGBA{0xc5, 0xc8, 0xc6, 0xff}
	themeBg     = color.RGBA{0x1d, 0x1f, 0x21, 0xff}
	themeCursor = color.RGBA{0xc5, 0xc8, 0xc6, 0xff}

	themePalette = [16]color.Color{
		color.RGBA{0x28, 0x2a, 0x2e, 0xff}, // black
		color.RGBA{0xcc, 0x66, 0x66, 0xff}, // red
		color.RGBA{0xb5, 0xbd, 0x68, 0xff}, // green
		color.RGBA{0xf0, 0xc6, 0x74, 0xff}, // yellow
		color.RGBA{0x81, 0xa2, 0xbe, 0xff}, // blue
		color.RGBA{0xb2, 0x94, 0xbb, 0xff}, // magenta
		color.RGBA{0x8a, 0xbe, 0xb7, 0xff}, // cyan
		color.RGBA{0xc5, 0xc8, 0xc6, 0xff}, // white
		color.RGBA{0x96, 0x98, 0x96, 0xff}, // bright black
		color.RGBA{0xd5, 0x4e, 0x53, 0xff}, // bright red
		color.RGBA{0xb9, 0xca, 0x4a, 0xff}, // bright green
		color.RGBA{0xe7, 0xc5, 0x47, 0xff}, // bright yellow
		color.RGBA{0x7a, 0xa6, 0xda, 0xff}, // bright blue
		color.RGBA{0xc3, 0x97, 0xd8, 0xff}, // bright magenta
		color.RGBA{0x70, 0xc0, 0xb1, 0xff}, // bright cyan
		color.RGBA{0xea, 0xea, 0xea, 0xff}, // bright white
	}
)

// defaultPalette is palette entry n before any OSC 4 change.
func defaultPalette(n int) color.Color {
	if n < len(themePalette) {
		return themePalette[n]
	}
	return ansi.IndexedColor(n)
}
